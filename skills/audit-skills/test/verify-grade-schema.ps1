$ErrorActionPreference = 'Stop'

$root = Join-Path $PSScriptRoot '..'
$skill = Get-Content -LiteralPath (Join-Path $root 'SKILL.md') -Raw
$brief = Get-Content -LiteralPath (Join-Path $root 'audit-brief.md') -Raw

# Closed vocabulary: changing a grade, dropping polish, or adding a fifth value
# must fail the worker contract rather than producing incomparable audit results.
$grades = 'Good|Polish|Reliability|Broken'
$expectedResultSchema = "`"grades`": { `"reach`": `"$grades`", `"impl`": `"$grades`", `"correctness`": `"$grades`", `"utility`": `"$grades`" }"

if ($brief -notmatch [regex]::Escape($expectedResultSchema)) {
    throw 'Worker result grades must use the closed four-name vocabulary on every axis.'
}

if ($skill -notmatch [regex]::Escape('Every worker result uses the closed grade vocabulary: Good, Polish, Reliability, Broken.')) {
    throw 'Skill must require the same closed grade vocabulary as the worker result.'
}

# The controller, not a routed reference, owns every executable output decision.
foreach ($needle in @(
    'defect scale: Broken, Reliability, Polish, and Good.',
    'Utility uses the lifecycle scale:',
    # Placeholdered 2026-09-19. The controller no longer hardcodes the machine-local
    # vault root, which every third-party runtime mounting this skill was reading
    # verbatim. The report SHAPE is still the controller's to own, so the path stays
    # asserted here; only its root now resolves from the runtime instructions.
    '<vault>\Claude\SkillAudits\SkillAudit-YYYY-MM-DD.md',
    '# Skill Audit — YYYY-MM-DD',
    '> Generated by audit-skills · <N> owned skills · <S> runtime surfaces',
    'Skill | Reach | Impl | Correctness | Utility | Top issue',
    'Skill | Disposition | Confidence | Evidence',
    'exact evidence',
    'precise unapplied fix',
    'impact <h/m/l> · effort <l/m/h>',
    'In chat return only the verdict, scorecard, top fixes, and report path'
)) {
    if ($skill -notmatch [regex]::Escape($needle)) {
        throw "Controller output contract is missing: $needle"
    }
}
foreach ($section in 'Verdict', 'Broken', 'Reliability', 'Polish', 'Cross-skill', 'Lifecycle recommendations', 'Trend since <date>', 'Prioritized fixes') {
    if ($skill -notmatch [regex]::Escape($section)) {
        throw "Controller output contract is missing its section: $section"
    }
}

# Exposure (what a skill discloses to a model vendor) was removed as an axis on
# 2026-10-11 at the owner's direction: vendor disclosure is not a concern for this
# estate, and the axis produced most of a run's findings and cost. Keep it out.
foreach ($pair in @(@('SKILL.md', $skill), @('audit-brief.md', $brief))) {
    if ($pair[1] -match '(?i)exposure_findings|exposure_scope|Axis 5|exposure-classes|"exposure"') {
        throw "$($pair[0]) must not reintroduce the exposure axis."
    }
}
if (Test-Path -LiteralPath (Join-Path $root 'references/exposure-classes.md')) {
    throw 'references/exposure-classes.md belongs to the removed exposure axis.'
}

'audit-skills grade schema OK'
